export type TranslationKey = keyof typeof ptBR;

export function translate(language: AppLanguage, key: TranslationKey) {
  return (language === "it-IT" ? itIT : ptBR)[key];
}

export function loadAppLanguage(): AppLanguage {
  if (typeof window === "undefined") return "pt-BR";
  return localStorage.getItem(STORAGE_KEY) === "it-IT" ? "it-IT" : "pt-BR";
}

export function saveAppLanguage(language: AppLanguage) {
  localStorage.setItem(STORAGE_KEY, language);
  document.documentElement.lang = language;
  return language;
}
